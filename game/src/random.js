// A small seeded random source (mulberry32): the same seed always gives the same
// sequence, so a staged screenshot is reproducible. No Math.random anywhere in the
// simulation, so the game is deterministic for a given seed.

export function createRandom(seed) {
  let state = (seed >>> 0) || 0x9e3779b9;
  return {
    next() {
      state = (state + 0x6d2b79f5) >>> 0;
      let t = state;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    },
    range(min, max) {
      return min + this.next() * (max - min);
    },
    int(min, max) {
      return Math.floor(this.range(min, max + 1));
    },
    pick(items) {
      return items[Math.floor(this.next() * items.length)];
    },
  };
}
